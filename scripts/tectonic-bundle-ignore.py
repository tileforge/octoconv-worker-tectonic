#!/usr/bin/env python3
"""Add the generated package exclusions to a copy of upstream's bundle.toml.

Called by scripts/tectonic-bundle-build.sh. It lives in its own file rather
than inline in that script for a mundane reason worth stating: the rules it
writes are TOML triple-quoted strings, and nesting those inside a shell
heredoc inside a build script is how a quoting bug becomes a silently wrong
ignore list.

WHAT IT DOES, AND WHY IT IS AN INVERSION

tectonic-texlive-bundles selects by EXCLUSION. internal/convert/texpackages.go
is an allowlist. Rust's regex crate has no negative lookahead, so "keep only
these" cannot be one pattern -- the allowlist has to be compiled into one
exclusion per package directory that is present in the tree and not named.

The list of present directories comes from the tarball itself, not from a
package index, so a directory the tarball happens to carry under an unexpected
name is excluded rather than quietly included.
"""

import re
import sys


def main() -> int:
    if len(sys.argv) != 4:
        print("usage: tectonic-bundle-ignore.py <bundle.toml> <package-drops> <font-drops>",
              file=sys.stderr)
        return 2

    toml_path, drop_path, font_drop_path = sys.argv[1], sys.argv[2], sys.argv[3]

    with open(drop_path, encoding="utf-8") as fh:
        drops = [line.strip() for line in fh if line.strip()]
    with open(font_drop_path, encoding="utf-8") as fh:
        font_drops = [line.strip() for line in fh if line.strip()]
    if not drops:
        print("refusing to write an empty exclusion list: the drop list is empty, which would "
              "ship the whole of TeXLive", file=sys.stderr)
        return 1

    with open(toml_path, encoding="utf-8") as fh:
        src = fh.read()

    # Upstream's hash is for upstream's contents. Ours differ by construction,
    # so asserting theirs fails on the first run; asserting nothing makes the
    # builder print what we actually produced, which is the number to record.
    src = re.sub(r'expected_hash\s*=\s*"[^"]*"', 'expected_hash = ""', src, count=1)
    src = re.sub(r'name\s*=\s*"texlive2023"', 'name = "octoconv-reduced"', src, count=1)

    marker = '[inputs."texlive"]'
    try:
        idx = src.index(marker)
    except ValueError:
        print("upstream spec has no [inputs.\"texlive\"] section -- its shape changed and this "
              "generator must be re-read against it", file=sys.stderr)
        return 1

    m = re.search(r"ignore\s*=\s*\[", src[idx:])
    if m is None:
        print("the texlive input carries no ignore list -- upstream spec changed shape",
              file=sys.stderr)
        return 1
    insert_at = idx + m.end()

    quote = "'" * 3
    lines = [
        "",
        "    # --- generated by scripts/tectonic-bundle-build.sh from",
        "    # internal/convert/texpackages.go: every tex/latex package directory present",
        "    # in the tarball that the declared set does not name. Paths are relative to",
        "    # root_dir and must not start with a slash (doc/bundle.md).",
    ]
    for d in drops:
        lines.append("    %stex/latex/%s/.*%s," % (quote, re.escape(d), quote))
    # Fonts are 93% of the tree; the package exclusions above are 4% of it.
    # The path shape is fonts/<format>/<foundry>/<family>, so the family is the
    # third component and the two above it vary.
    for d in font_drops:
        lines.append("    %sfonts/[^/]*/[^/]*/%s/.*%s," % (quote, re.escape(d), quote))
    lines.append("    # --- end generated")
    lines.append("")

    with open(toml_path, "w", encoding="utf-8") as fh:
        fh.write(src[:insert_at] + "\n".join(lines) + src[insert_at:])

    print("  wrote %d generated ignore rules (%d package, %d font)"
          % (len(drops) + len(font_drops), len(drops), len(font_drops)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
